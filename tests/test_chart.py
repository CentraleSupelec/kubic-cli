"""One-line files of the helm/argocd chart (helpers in templates/_helpers.tpl)."""
from pathlib import Path

from typer.testing import CliRunner

from kubic_cli import chart
from kubic_cli.main import app

ACC = "helm/argocd/templates/k8s-accounts"

LEGACY = """# Generated by kubic-cli
apiVersion: v1
kind: ServiceAccount
metadata:
  name: alice
  namespace: default
---
apiVersion: rbac.authorization.k8s.io/v1
kind: RoleBinding
metadata:
  name: alice
  namespace: other-prod
subjects:
  - kind: ServiceAccount
    name: alice
    namespace: default
roleRef:
  apiGroup: rbac.authorization.k8s.io
  kind: ClusterRole
  name: admin
"""


def test_repository_content_derives_git_host():
    assert chart.repository_content("demo", "git@host:g/demo.git", "host") == (
        "# Argo CD repository of demo (helper in _helpers.tpl)\n"
        '{{ include "argocd.repository" (dict "name" "demo" "url" "git@host:g/demo.git" "root" $) }}\n')


def test_repository_content_passes_host_of_other_urls():
    content = chart.repository_content("demo", "ssh://git@host:2222/g/demo.git", "host-2222")
    assert '"url" "ssh://git@host:2222/g/demo.git" "host" "host-2222" "root" $' in content


def test_vault_token_content():
    assert chart.vault_token_content("demo").splitlines()[1] == \
        '{{ include "argocd.vaultToken" (dict "name" "demo" "root" $) }}'


def test_user_content_and_namespaces():
    content = chart.user_content("alice", ["demo-dev", "demo-prod"])
    assert content.splitlines()[1] == \
        '{{ include "argocd.k8sUser" (dict "name" "alice" "namespaces" (list "demo-dev" "demo-prod")) }}'
    assert chart.user_namespaces(content) == ["demo-dev", "demo-prod"]
    assert chart.user_namespaces(chart.user_content("alice", [])) == []
    assert chart.user_namespaces(LEGACY) == ["other-prod"]


def test_add_user_namespaces_one_line(tmp_path: Path):
    f = tmp_path / "user-alice.yaml"
    f.write_text('# x\n{{ include "argocd.k8sUser" (dict "name" "alice" "namespaces" (list "a") '
                 '"clusterRoles" (list "admin") "token" false) }}\n')
    assert chart.add_user_namespaces(f, "alice", ["a", "b"]) == ["b"]
    assert f.read_text() == ('# x\n{{ include "argocd.k8sUser" (dict "name" "alice" "namespaces" (list "a" "b") '
                             '"clusterRoles" (list "admin") "token" false) }}\n')
    assert chart.add_user_namespaces(f, "alice", ["a", "b"]) == []


def test_add_user_namespaces_without_list(tmp_path: Path):
    f = tmp_path / "user-bob.yaml"
    f.write_text(chart.user_content("bob", []))
    chart.add_user_namespaces(f, "bob", ["demo"])
    assert f.read_text() == chart.user_content("bob", ["demo"])


def test_add_user_namespaces_legacy_file_appends(tmp_path: Path):
    f = tmp_path / "user-alice.yaml"
    f.write_text(LEGACY)
    assert chart.add_user_namespaces(f, "alice", ["other-prod", "demo-prod"]) == ["demo-prod"]
    text = f.read_text()
    assert text.startswith(LEGACY) and text.count("kind: RoleBinding") == 2
    assert chart.user_namespaces(text) == ["other-prod", "demo-prod"]


def _run(*args):
    return CliRunner().invoke(app, list(args))


def test_create_project_then_add_environment_write_one_liners(tmp_path: Path):
    gp = str(tmp_path)
    r = _run("create-project", "demo", "--repo-url", "git@host:g/demo.git", "--envs", "prod", "--avp",
             "--vault-addr", "https://vault", "--skip-vault", "--devs", "alice", "--gitops-path", gp)
    assert r.exit_code == 0, r.output
    t = tmp_path / "helm/argocd/templates"
    assert (t / "repository/repository-demo.yaml").read_text() == \
        chart.repository_content("demo", "git@host:g/demo.git", "host")
    assert (t / "vault/vault-token-demo.yaml").read_text() == chart.vault_token_content("demo")
    assert (tmp_path / ACC / "user-alice.yaml").read_text() == chart.user_content("alice", ["demo-prod"])

    r = _run("add-environment", "demo", "--envs", "preprod", "--avp", "--skip-vault",
             "--gitops-path", gp)
    assert r.exit_code == 0, r.output
    assert (tmp_path / ACC / "user-alice.yaml").read_text() == \
        chart.user_content("alice", ["demo-prod", "demo-preprod"])


def test_create_project_existing_legacy_account(tmp_path: Path):
    (tmp_path / ACC).mkdir(parents=True)
    f = tmp_path / ACC / "user-alice.yaml"
    f.write_text(LEGACY)
    r = _run("create-project", "demo", "--repo-url", "git@host:g/demo.git", "--envs", "prod", "--avp",
             "--skip-vault", "--devs", "alice", "--gitops-path", str(tmp_path))
    assert r.exit_code == 0, r.output
    assert chart.user_namespaces(f.read_text()) == ["other-prod", "demo-prod"]
