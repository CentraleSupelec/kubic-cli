"""YAML data files of the helm/argocd chart (rendered by the helpers of templates/_helpers.tpl)."""
from pathlib import Path

import yaml
from typer.testing import CliRunner

from kubic_cli import chart
from kubic_cli.main import app

USERS = "helm/argocd/users"
LEGACY_DIR = "helm/argocd/templates/k8s-accounts"

LEGACY = """# Generated by kubic-cli
apiVersion: v1
kind: ServiceAccount
metadata:
  name: alice
  namespace: default
---
apiVersion: rbac.authorization.k8s.io/v1
kind: RoleBinding
metadata:
  name: alice
  namespace: other-prod
subjects:
  - kind: ServiceAccount
    name: alice
    namespace: default
roleRef:
  apiGroup: rbac.authorization.k8s.io
  kind: ClusterRole
  name: admin
"""


def test_dump_is_stable_and_indented():
    data = {"name": "alice", "token": False, "clusterRoles": ["admin"], "namespaces": ["b", "a"]}
    assert chart.dump(data) == ("name: alice\ntoken: false\nclusterRoles:\n  - admin\n"
                                "namespaces:\n  - b\n  - a\n")
    assert yaml.safe_load(chart.dump(data)) == data


def test_repository_data_derives_git_host():
    assert chart.repository_data("demo", "git@host:g/demo.git", "host") == \
        {"name": "demo", "url": "git@host:g/demo.git"}
    assert chart.repository_data("demo", "ssh://git@host:2222/g/demo.git", "host-2222") == \
        {"name": "demo", "url": "ssh://git@host:2222/g/demo.git", "host": "host-2222"}


def test_user_data():
    assert chart.user_data("alice", []) == {"name": "alice"}
    assert chart.user_data("alice", ["a"]) == {"name": "alice", "namespaces": ["a"]}


def test_add_user_namespaces_data_file_keeps_other_keys(tmp_path: Path):
    f = tmp_path / "users" / "alice.yaml"
    f.parent.mkdir()
    f.write_text("name: alice\ntoken: false\nnamespaces:\n  - a\nclusterRoles:\n  - admin\n")
    assert chart.add_user_namespaces(f, "alice", ["a", "b"]) == ["b"]
    assert f.read_text() == "name: alice\ntoken: false\nnamespaces:\n  - a\n  - b\nclusterRoles:\n  - admin\n"
    assert chart.add_user_namespaces(f, "alice", ["a", "b"]) == []


def test_add_user_namespaces_without_list(tmp_path: Path):
    f = tmp_path / "users" / "bob.yaml"
    f.parent.mkdir()
    f.write_text(chart.dump(chart.user_data("bob", [])))
    chart.add_user_namespaces(f, "bob", ["demo"])
    assert f.read_text() == chart.dump(chart.user_data("bob", ["demo"]))


def test_add_user_namespaces_legacy_file_appends(tmp_path: Path):
    f = tmp_path / "user-alice.yaml"
    f.write_text(LEGACY)
    assert chart.user_namespaces(f) == ["other-prod"]
    assert chart.add_user_namespaces(f, "alice", ["other-prod", "demo-prod"]) == ["demo-prod"]
    assert f.read_text().startswith(LEGACY)
    assert chart.user_namespaces(f) == ["other-prod", "demo-prod"]


def test_user_file_prefers_existing_legacy(tmp_path: Path):
    assert chart.user_file(tmp_path, "alice") == tmp_path / USERS / "alice.yaml"
    (tmp_path / LEGACY_DIR).mkdir(parents=True)
    (tmp_path / LEGACY_DIR / "user-alice.yaml").write_text(LEGACY)
    assert chart.user_file(tmp_path, "alice") == tmp_path / LEGACY_DIR / "user-alice.yaml"
    assert chart.user_files(tmp_path) == {"alice": tmp_path / LEGACY_DIR / "user-alice.yaml"}


def _run(*args):
    return CliRunner().invoke(app, list(args))


def test_create_project_then_add_environment_write_data_files(tmp_path: Path):
    gp = str(tmp_path)
    r = _run("create-project", "demo", "--repo-url", "git@host:g/demo.git", "--envs", "prod", "--avp",
             "--vault-addr", "https://vault", "--skip-vault", "--devs", "alice", "--gitops-path", gp)
    assert r.exit_code == 0, r.output
    c = tmp_path / "helm/argocd"
    assert (c / "repositories/demo.yaml").read_text() == "name: demo\nurl: git@host:g/demo.git\n"
    assert (c / "vault-tokens/demo.yaml").read_text() == "name: demo\n"
    assert (c / "users/alice.yaml").read_text() == "name: alice\nnamespaces:\n  - demo-prod\n"

    r = _run("add-environment", "demo", "--envs", "preprod", "--avp", "--skip-vault", "--gitops-path", gp)
    assert r.exit_code == 0, r.output
    assert (c / "users/alice.yaml").read_text() == "name: alice\nnamespaces:\n  - demo-prod\n  - demo-preprod\n"


def test_create_project_keeps_legacy_files(tmp_path: Path):
    t = tmp_path / "helm/argocd/templates"
    (t / "k8s-accounts").mkdir(parents=True)
    (t / "repository").mkdir()
    (t / "k8s-accounts/user-alice.yaml").write_text(LEGACY)
    (t / "repository/repository-demo.yaml").write_text("legacy\n")
    r = _run("create-project", "demo", "--repo-url", "git@host:g/demo.git", "--envs", "prod", "--avp",
             "--skip-vault", "--devs", "alice", "--gitops-path", str(tmp_path))
    assert r.exit_code == 0, r.output
    assert chart.user_namespaces(t / "k8s-accounts/user-alice.yaml") == ["other-prod", "demo-prod"]
    assert (t / "repository/repository-demo.yaml").read_text() == "legacy\n"
    assert not (tmp_path / "helm/argocd/users").exists() and not (tmp_path / "helm/argocd/repositories").exists()
