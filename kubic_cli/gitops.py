import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Dict, List, Optional
import typer

__all__ = ["ensure_account", "ensure_rbac", "generate_appprojects"]


def ensure_account(cm_path: Path, user: str, dry_run: bool = False):
    """Ajoute accounts.<user>: apiKey,login dans argocd-cm."""
    if not cm_path.exists():
        typer.secho(f"[WARN] {cm_path} introuvable, compte {user} ignoré", fg=typer.colors.YELLOW)
        return

    text = cm_path.read_text()
    if f"accounts.{user}:" in text:
        return

    lines = text.splitlines(keepends=True)
    insert_idx = next((i for i,l in enumerate(lines) if l.startswith("  accounts.")), None)
    if insert_idx is None:
        insert_idx = next((i for i,l in enumerate(lines) if l.strip()=="data:"), None)
    if insert_idx is None:
        typer.secho("[ERROR] Impossible d'insérer le compte dans argocd-cm", fg=typer.colors.RED)
        return

    account_block = f"  # generated by kubic-cli\n  accounts.{user}: apiKey,login\n"
    lines.insert(insert_idx+1, account_block)
    if not dry_run:
        cm_path.write_text("".join(lines))
    typer.echo(f"{'[DRY-RUN] ' if dry_run else ''}[UPDATE] Compte {user} ajouté dans argocd-cm.yaml")


def ensure_rbac(rbac_path: Path, slug: str, devs: List[str], dry_run: bool = False):
    """Garantit que le rôle projet et mappings g,<user>,role existent."""
    if not rbac_path.exists():
        typer.secho(f"[WARN] {rbac_path} introuvable, RBAC non modifié", fg=typer.colors.YELLOW)
        return

    lines = rbac_path.read_text().splitlines(keepends=True)
    indent = "    "
    role_present = any(f"role:{slug}, applications" in l for l in lines)

    modified = False
    if not role_present:
        block = ["\n", f"{indent}# Auto-generated for {slug} – kubic-cli\n"]
        # No create/update: tenants must not change their Application spec (source type, destination)
        for verb in ["delete","get","override","sync"]:
            # Each project has its own AppProject named <slug>: the default project holds no app.
            # Exact project: a <slug>* glob would also reach a project named <slug>-other
            block.append(f"{indent}p, role:{slug}, applications, {verb}, {slug}/{slug}*, allow\n")
        for dev in devs:
            block.append(f"{indent}g, {dev}, role:{slug}\n")
        lines.extend(block)
        modified = True
    else:
        for dev in devs:
            map_line = f"{indent}g, {dev}, role:{slug}\n"
            if not any(map_line.strip()==l.strip() for l in lines):
                lines.append(map_line)
                modified = True
    if modified:
        if not dry_run:
            rbac_path.write_text("".join(lines))
        typer.echo(f"{'[DRY-RUN] ' if dry_run else ''}[UPDATE] RBAC mis à jour pour {slug}")


def generate_appprojects(gitops_path: Path, dry_run: bool = False, pending: Optional[Dict[Path, str]] = None):
    """Regenerate the AppProjects of the GitOps repo from apps/<slug>/*.json.
    dry_run: --check on a copy of the repo holding the JSON not yet written (pending: path -> content)."""
    script = gitops_path / "scripts" / "gen-appprojects.py"
    if not script.exists():
        typer.secho(f"[WARN] {script} introuvable, AppProject non généré", fg=typer.colors.YELLOW)
        return
    if dry_run:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp) / "gitops"
            shutil.copytree(gitops_path, root, ignore=shutil.ignore_patterns(".git"))
            for path, content in (pending or {}).items():
                target = root / Path(path).relative_to(gitops_path)
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content)
            r = subprocess.run([sys.executable, str(root / "scripts" / "gen-appprojects.py"), "--check"],
                               cwd=root, capture_output=True, text=True)
        typer.echo("[EXISTS] AppProjects à jour" if r.returncode == 0
                   else f"[DRY-RUN] [UPDATE] AppProjects :\n{r.stdout}{r.stderr}".rstrip())
        return
    r = subprocess.run([sys.executable, str(script)], cwd=gitops_path, capture_output=True, text=True)
    if r.returncode != 0:
        typer.secho(f"[ERROR] gen-appprojects.py a échoué :\n{r.stdout}{r.stderr}", fg=typer.colors.RED)
        raise typer.Exit(1)
    typer.echo(f"[UPDATE] AppProjects : {r.stdout.strip()}")
